function applyLanguage(lang) {
  const dict = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    // XSS Risk: innerHTML is used intentionally because some translation values contain HTML markup
    // (e.g., contact.form.note embeds an <a> tag, values use &amp; entities). Current risk: LOW
    // (all values are hardcoded developer-controlled strings). Future risk: HIGH if translations
    // are ever loaded from an external URL, CMS, or user-controlled input. Do NOT change to textContent.
    if (dict[key]) el.innerHTML = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.setAttribute("placeholder", dict[key]);
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
  localStorage.setItem("order4u-lang", lang);
}

document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
});

applyLanguage(localStorage.getItem("order4u-lang") || "en");

